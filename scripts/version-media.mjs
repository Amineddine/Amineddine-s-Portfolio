// Gives rendered media content-hashed filenames so browsers/CDNs can never
// serve a stale copy (Vercel caches /public files for hours under a fixed name;
// a <video> keeps playing the old reel even after a hard refresh).
//
// Drop freshly rendered files into /public under their plain names, then run:
//   node scripts/version-media.mjs
// Each plain file becomes <stem>.<hash8>.<ext>, older hashed copies are
// deleted, and src/data/media.ts is regenerated with the current paths.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";

const PUBLIC = path.resolve("public");
const MEDIA = {
  reelWebm: "cold-open.webm",
  reelMp4: "cold-open.mp4",
  reelPoster: "cold-open-poster.webp",
  aboutCard: "about-card.mp4",
};

const out = {};
for (const [key, plain] of Object.entries(MEDIA)) {
  const ext = path.extname(plain);
  const stem = plain.slice(0, -ext.length);
  const hashed = new RegExp(`^${stem.replace(/[-.]/g, "\\$&")}\\.[0-9a-f]{8}\\${ext}$`);
  const plainPath = path.join(PUBLIC, plain);

  if (existsSync(plainPath)) {
    const hash = createHash("sha256").update(readFileSync(plainPath)).digest("hex").slice(0, 8);
    const name = `${stem}.${hash}${ext}`;
    for (const f of readdirSync(PUBLIC)) if (hashed.test(f) && f !== name) unlinkSync(path.join(PUBLIC, f));
    renameSync(plainPath, path.join(PUBLIC, name));
    out[key] = `/${name}`;
  } else {
    const current = readdirSync(PUBLIC).filter((f) => hashed.test(f));
    if (current.length !== 1) throw new Error(`${plain}: expected one hashed file, found ${current.length}`);
    out[key] = `/${current[0]}`;
  }
  console.log(`${key.padEnd(10)} ${out[key]}`);
}

writeFileSync(
  path.resolve("src/data/media.ts"),
  `// GENERATED by scripts/version-media.mjs — do not edit by hand.
// Content-hashed media paths: a new render gets a new URL, so no cache can
// serve a stale video.
export const MEDIA = ${JSON.stringify(out, null, 2)} as const;
`,
);
